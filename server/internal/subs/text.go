package subs

import (
	"strings"
	"unicode/utf8"
)

// bom — UTF-8 BOM. В исходнике Go литеральный U+FEFF это ошибка компиляции
// («illegal byte order mark»), поэтому только байтами.
const bom = "\xef\xbb\xbf"

// decode приводит содержимое файла субтитров к UTF-8.
//
// Кодировка нужна не для красоты: русские раздачи субтитров до сих пор наполовину
// лежат в CP1251. В том паке, ради которого это написано, 115 файлов из 234 —
// UTF-8 с BOM, а остальные 119 — CP1251 без всяких признаков. Разложить их
// заранее руками можно ровно один раз, а следующий пак приедет таким же.
//
// Признак выбран самый надёжный из возможных: текст в CP1251 почти никогда
// не проходит проверку на корректный UTF-8, потому что кириллица там —
// это одиночные байты 0xC0-0xFF, а UTF-8 требует после них байт
// продолжения 0x80-0xBF. Обратной ошибки (UTF-8, прочитанный как CP1251)
// быть не может: до таблицы дело дойдёт, только если UTF-8 не разобрался.
func decode(raw []byte) string {
	s := strings.TrimPrefix(string(raw), bom)
	if utf8.ValidString(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s) * 2)
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 0x80 {
			b.WriteByte(c)
			continue
		}
		b.WriteRune(cp1251[c-0x80])
	}
	return b.String()
}

