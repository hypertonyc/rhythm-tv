package mediasource

import (
	g "github.com/anacrolix/generics"
	"github.com/anacrolix/torrent/storage"
)

// Part-файлы anacrolix выключены, и это несущее решение, а не вкус.
//
// Оставленное на усмотрение библиотеки хранилище (ClientConfig.DefaultStorage
// == nil → storage.NewFile) включает part-файлы: UsePartFiles по умолчанию
// true (storage.NewFileClientOpts.partFiles). Незавершённый файл лежит тогда
// как "<имя>.part" и по завершении переименовывается в "<имя>". Схема молча
// уничтожает уже скачанные серии, потому что три её свойства складываются:
//
//  1. pathForWrite отдаёт путь ".part" ВСЕГДА — даже если рядом лежит готовый
//     "<имя>". А openForWrite открывает его с O_CREATE.
//  2. Куски не выровнены по границам файлов: последний кусок серии N — он же
//     первый кусок серии N+1, и WriteAt такого куска пишет в ОБА файла.
//  3. Чтение предпочитает ".part" готовому "<имя>" (openFile, openSharedFile).
//
// Поэтому запись граничного куска при скачивании серии N+1 создаёт рядом
// с готовой серией N разреженный ".part" полного размера. С этого момента
// серия N читается нулями, хотя данные ещё целы — так сеанс перекодирования
// умирает посреди серии, не написав ни одной ошибки. А MarkComplete на том же
// куске видит, что все куски серии N готовы, и зовёт promotePartFile, который
// делает os.Rename(".part" → "<имя>"), то есть кладёт пустышку ПОВЕРХ настоящих
// данных. 300 МБ уходят навсегда, а файл остаётся полного размера и read-only,
// внешне неотличимый от честно скачанного, — это и есть фантом из phantom.go.
//
// Спусковой крючок — любой готовый кусок, с которого сняли отметку:
//
//   - перезапуск процесса: setCompletionFromPartFiles снимает отметку со ВСЕХ
//     кусков каждого ".part"-файла, включая граничные, принадлежащие готовым
//     соседям. То есть каждая выкатка заряжала мину на оба соседних файла
//     у каждого недокачанного;
//   - провал хэша от плохого пира (в логе — "smart banned peer");
//   - наше же лечение фантомов: VerifyData по кускам файла задевает граничные.
//
// Так были потеряны s03e04 и s01e04 «Друзей», S08E01 и S07E22 tbbt. Версия
// v1.61.0 стоит с первого коммита Go-сервера, так что баг работал с первого
// дня порта; в Node этого не было, потому что part-файлов у webtorrent нет.
// Новее v1.61.0 в апстриме нет — починить обновлением нельзя.
//
// С выключенными part-файлами запись идёт прямо в "<имя>", переименований нет,
// и подменить готовый файл нечем. Отметки готовности остаются в том же
// .torrent.bolt.db рядом с данными (при UsePartFiles=false PieceCompletion
// по умолчанию — pieceCompletionForDir), так что скачанное не перекачивается.
//
// Всё вышесказанное держат тесты в partfile_test.go: два фиксируют поведение
// апстрима (и упадут, если его когда-нибудь исправят), третий — что наше
// хранилище мимо него.
func newStore(dataDir string) storage.ClientImplCloser {
	return storage.NewFileOpts(storage.NewFileClientOpts{
		ClientBaseDir: dataDir,
		UsePartFiles:  g.Some(false),
		// Логгер хранилища иначе уедет в slog.Default(). Свой нужен затем,
		// что предупреждение "file too small for piece marked as complete" —
		// это ровно тот фантом, который ловит phantom.go, и терять его нельзя.
		Logger: quietSlogger(),
	})
}
