package mediasource

import (
	"context"
	"log"
	"path/filepath"

	"github.com/anacrolix/torrent"
)

// Фантомный файл — тот, который торрент считает скачанным целиком, а на диске
// под ним почти нет блоков.
//
// Так выглядела авария 16.08.2026: три серии числились готовыми, занимая
// на диске 0–1% своего размера. Отметка «кусок готов» лежит в .torrent.bolt.db
// рядом с данными и переживает перезапуск, поэтому состояние само себя
// поддерживает: читатель не блокируется и в рой не идёт, а мгновенно отдаёт
// нули. Наружу это не отказ, а порча. ffmpeg получает валидное начало файла
// и нули дальше, сегменты нарезаются, картинка идёт, а дорожка субтитров
// выходит пустой — из 44 сегментов VTT непустым был один. Ни сервер, ни
// телевизор при этом не пишут ни одной ошибки, и увидеть это можно только
// глазами по отсутствующим субтитрам.
//
// Причина появления таких файлов не установлена, поэтому проверка идёт при
// каждом старте, а не разово: она стоит одного stat на файл, а молча
// испорченный вечер стоит дороже.
const (
	// phantomMinLength — порог, ниже которого файл не проверяется. Мелочь
	// вроде .nfo и превью занимает считанные блоки, и отношение занятого
	// к размеру у неё скачет само по себе.
	phantomMinLength = 16 << 20

	// phantomMaxShare — доля размера, ниже которой занятое место считается
	// невозможным для честно скачанного файла. Половина взята с большим
	// запасом: у настоящей аварии было 0–1%, а у целых файлов — 95%+.
	// Запас нужен под файловые системы, которые умеют сжатие: там занятого
	// законно меньше, чем размера, и порог в 90% давал бы ложные срабатывания.
	phantomMaxShare = 0.5
)

// isPhantom решает по размеру и занятому месту, врёт ли отметка готовности.
//
// Дырка в файле — надёжный признак именно НЕ записанных данных: нулевые байты,
// которые кто-то записал, блоки занимают, а не записанные вовсе — нет.
// Поэтому смотрим на выделенные блоки, а не на размер, который у разреженного
// файла ровно такой же, как у целого.
func isPhantom(length, allocated int64) bool {
	if length < phantomMinLength {
		return false
	}
	return float64(allocated) < float64(length)*phantomMaxShare
}

// healPhantomFiles снимает ложные отметки готовности, перепроверяя хэши
// подозрительных файлов. Недостающее после этого докачается по требованию,
// как и любые другие отсутствующие куски.
//
// Возвращает число вылеченных файлов — ради теста и лога, больше это никому
// не нужно.
func healPhantomFiles(ctx context.Context, t *torrent.Torrent, dataDir string) int {
	healed := 0
	for _, f := range t.Files() {
		if f.BytesCompleted() != f.Length() {
			// Файл и так не считается целым: недостающее докачается само,
			// перепроверять нечего.
			continue
		}
		allocated, err := allocatedBytes(filepath.Join(dataDir, f.Path()))
		if err != nil {
			log.Printf("phantom check %q: %v (пропускаю)", f.Path(), err)
			continue
		}
		if !isPhantom(f.Length(), allocated) {
			continue
		}

		log.Printf("phantom file %q: числится скачанным (%s), на диске %s — перепроверяю куски",
			f.Path(), humanBytes(f.Length()), humanBytes(allocated))
		for i := range f.PieceIndices() {
			if ctx.Err() != nil {
				return healed
			}
			if err := t.Piece(i).VerifyDataContext(ctx); err != nil {
				log.Printf("phantom file %q: кусок %d: %v", f.Path(), i, err)
			}
		}
		healed++
		log.Printf("phantom file %q: после перепроверки числится %s",
			f.Path(), humanBytes(f.BytesCompleted()))
	}
	return healed
}
