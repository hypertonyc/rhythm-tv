package mediasource

import (
	"log"
	"os"
)

// storageFileIoEnv выбирает у anacrolix реализацию файлового ввода-вывода.
// Переменная читается в init() пакета storage, поэтому выставить её из своего
// кода нельзя ВООБЩЕ: инициализация зависимостей идёт раньше main. Она задаётся
// снаружи — в server/Dockerfile (значит, в любом запуске образа) и явно
// в deploy/compose.yaml, где описан прод.
const storageFileIoEnv = "TORRENT_STORAGE_DEFAULT_FILE_IO"

// classicFileIo — единственное годное здесь значение, и вот почему.
//
// Умолчание библиотеки — mmap (storage/file-io-mmap.go, init): каждый файл
// хранилища отображается в память при первом обращении и НЕ ОТПУСКАЕТСЯ
// никогда. В апстриме это записано прямо над кэшем: «Currently the store never
// relinquishes its extra ref so we never clean up anyway». Пока отображение
// живо, inode удалённого файла живёт вместе с ним, то есть os.Remove
// не освобождает на диске ни одного блока.
//
// Для сервера это означает, что чистка места (internal/reclaim) перестаёт
// работать, оставаясь при этом внешне исправной: 02.09.2026 она выселила
// 579 файлов на 141 ГБ, а свободного места на VPS не появилось ни байта —
// в логе минуту за минутой шло «надо освободить 19.8 ГБ, кандидатов 0»,
// df показывал 94 ГБ занятыми при 4.9 ГБ настоящих файлов, и 89 ГБ из них
// держали 393 удалённые серии в /proc/<pid>/map_files. Дальше запись куска
// упёрлась в ENOSPC, anacrolix навсегда выключил скачивание (см. onWriteChunkErr
// в anacrolix.go), и телевизор получил чёрный экран.
//
// Классический путь (pread/pwrite) отображений не делает и хэндлы не кэширует
// (storage/file-handle-cache.go: regularFsSharedFiles), так что удаление файла
// освобождает место сразу. Всё, чем платим, — системный вызов на чтение вместо
// обращения к памяти; на нашей нагрузке (одно последовательное чтение серии
// петлёй через /raw) это не видно.
//
// Отдать выбор через storage.NewFileClientOpts нельзя: поля под реализацию
// ввода-вывода в опциях нет, только эта переменная окружения.
const classicFileIo = "classic"

// warnUnlessClassicFileIo кричит в лог, если сервер запущен с mmap-хранилищем.
//
// Молчать здесь нельзя: mmap ломает не воспроизведение, а чистку места, и
// увидеть это можно только через несколько дней и только по df — сервер
// при этом выглядит совершенно здоровым.
func warnUnlessClassicFileIo() {
	if os.Getenv(storageFileIoEnv) == classicFileIo {
		return
	}
	log.Printf("ВНИМАНИЕ: %s не равно %q (сейчас %q) — хранилище работает через mmap "+
		"и не отпускает удалённые файлы, то есть чистка места не освободит ни байта. "+
		"См. internal/mediasource/fileio.go",
		storageFileIoEnv, classicFileIo, os.Getenv(storageFileIoEnv))
}
